-- T_IDOSO
CREATE TABLE T_IDOSO (
    ID               NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    NOME             VARCHAR2(80)    NOT NULL,
    CPF              VARCHAR2(11)    NOT NULL,
    TELEFONE         VARCHAR2(11)    NOT NULL,
    BAIRRO           VARCHAR2(60)    NOT NULL,
    DATA_NASCIMENTO  DATE            NOT NULL,
    LIMITE_PIX       NUMBER(10,2)    DEFAULT 500 NOT NULL,
    CONSTRAINT PK_T_IDOSO PRIMARY KEY (ID),
    CONSTRAINT UN_IDOSO_CPF UNIQUE (CPF),
    CONSTRAINT CK_IDOSO_CPF CHECK (LENGTH(CPF) = 11),
    CONSTRAINT CK_IDOSO_LIMITE CHECK (LIMITE_PIX >= 0)
);

-- T_GUARDIAO
CREATE TABLE T_GUARDIAO (
    ID        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    NOME      VARCHAR2(80)    NOT NULL,
    CPF       VARCHAR2(11)    NOT NULL,
    TELEFONE  VARCHAR2(11)    NOT NULL,
    EMAIL     VARCHAR2(100)   NOT NULL,
    CONSTRAINT PK_T_GUARDIAO PRIMARY KEY (ID),
    CONSTRAINT UN_GUARDIAO_CPF UNIQUE (CPF),
    CONSTRAINT UN_GUARDIAO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_GUARDIAO_CPF CHECK (LENGTH(CPF) = 11)
);

-- T_VINCULO (tabela associativa: um idoso tem vários guardiões e um guardião cuida de vários idosos)
CREATE TABLE T_VINCULO (
    ID_IDOSO      NUMBER(10)      NOT NULL,
    ID_GUARDIAO   NUMBER(10)      NOT NULL,
    PARENTESCO    VARCHAR2(30)    NOT NULL,
    PRIORIDADE    NUMBER(1)       NOT NULL,
    DATA_VINCULO  DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_T_VINCULO PRIMARY KEY (ID_IDOSO, ID_GUARDIAO),
    CONSTRAINT CK_VINCULO_PRIORIDADE CHECK (PRIORIDADE BETWEEN 1 AND 5)
);

-- T_EMPRESA
CREATE TABLE T_EMPRESA (
    ID     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    NOME   VARCHAR2(80)    NOT NULL,
    CNPJ   VARCHAR2(14)    NOT NULL,
    SETOR  VARCHAR2(20)    NOT NULL,
    CONSTRAINT PK_T_EMPRESA PRIMARY KEY (ID),
    CONSTRAINT UN_EMPRESA_CNPJ UNIQUE (CNPJ),
    CONSTRAINT CK_EMPRESA_CNPJ CHECK (LENGTH(CNPJ) = 14),
    CONSTRAINT CK_EMPRESA_SETOR CHECK (SETOR IN ('ENERGIA','AGUA','GAS','TELECOM','ENTREGA','OUTRO'))
);

-- T_PRESTADOR
CREATE TABLE T_PRESTADOR (
    ID          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    ID_EMPRESA  NUMBER(10)      NOT NULL,
    NOME        VARCHAR2(80)    NOT NULL,
    CPF         VARCHAR2(11)    NOT NULL,
    FUNCAO      VARCHAR2(50)    NOT NULL,
    CONSTRAINT PK_T_PRESTADOR PRIMARY KEY (ID),
    CONSTRAINT UN_PRESTADOR_CPF UNIQUE (CPF),
    CONSTRAINT CK_PRESTADOR_CPF CHECK (LENGTH(CPF) = 11)
);

-- T_VISITA
CREATE TABLE T_VISITA (
    ID              NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    ID_IDOSO        NUMBER(10)      NOT NULL,
    ID_PRESTADOR    NUMBER(10),
    NOME_VISITANTE  VARCHAR2(80),
    DATA_AGENDADA   DATE            NOT NULL,
    CODIGO          VARCHAR2(6)     NOT NULL,
    AGENDADO_POR    VARCHAR2(10)    NOT NULL,
    STATUS          VARCHAR2(12)    DEFAULT 'AGENDADA' NOT NULL,
    CONSTRAINT PK_T_VISITA PRIMARY KEY (ID),
    CONSTRAINT UN_VISITA_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_VISITA_CODIGO CHECK (LENGTH(CODIGO) = 6),
    CONSTRAINT CK_VISITA_AGENDADO CHECK (AGENDADO_POR IN ('EMPRESA','GUARDIAO')),
    CONSTRAINT CK_VISITA_STATUS CHECK (STATUS IN ('AGENDADA','CONFIRMADA','CANCELADA')),
    CONSTRAINT CK_VISITA_VISITANTE CHECK (ID_PRESTADOR IS NOT NULL OR NOME_VISITANTE IS NOT NULL)
);

-- T_SOLICITACAO (pedido de ajuda do idoso para os guardiões)
CREATE TABLE T_SOLICITACAO (
    ID                    NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100),
    ID_IDOSO              NUMBER(10)      NOT NULL,
    ID_GUARDIAO_RESPOSTA  NUMBER(10),
    ID_VISITA             NUMBER(10),
    TIPO                  VARCHAR2(10)    NOT NULL,
    DESCRICAO             VARCHAR2(400)   NOT NULL,
    VALOR                 NUMBER(10,2),
    CONTATO_SUSPEITO      VARCHAR2(150),
    STATUS                VARCHAR2(10)    DEFAULT 'PENDENTE' NOT NULL,
    ORIENTACAO            VARCHAR2(400),
    DATA_ABERTURA         DATE            DEFAULT SYSDATE NOT NULL,
    DATA_RESPOSTA         DATE,
    CONSTRAINT PK_T_SOLICITACAO PRIMARY KEY (ID),
    CONSTRAINT CK_SOLICITACAO_TIPO CHECK (TIPO IN ('VISITA','PIX','LIGACAO','LINK','MENSAGEM')),
    CONSTRAINT CK_SOLICITACAO_STATUS CHECK (STATUS IN ('PENDENTE','LIBERADA','BLOQUEADA')),
    CONSTRAINT CK_SOLICITACAO_VALOR CHECK (VALOR IS NULL OR VALOR > 0)
);

-- T_IDOSO -> T_VINCULO (excluir o idoso apaga os vínculos dele)
ALTER TABLE T_VINCULO
    ADD CONSTRAINT FK_VINCULO_IDOSO
    FOREIGN KEY (ID_IDOSO) REFERENCES T_IDOSO (ID)
    ON DELETE CASCADE;

-- T_GUARDIAO -> T_VINCULO
ALTER TABLE T_VINCULO
    ADD CONSTRAINT FK_VINCULO_GUARDIAO
    FOREIGN KEY (ID_GUARDIAO) REFERENCES T_GUARDIAO (ID)
    ON DELETE CASCADE;

-- T_EMPRESA -> T_PRESTADOR
ALTER TABLE T_PRESTADOR
    ADD CONSTRAINT FK_PRESTADOR_EMPRESA
    FOREIGN KEY (ID_EMPRESA) REFERENCES T_EMPRESA (ID);

-- T_IDOSO -> T_VISITA
ALTER TABLE T_VISITA
    ADD CONSTRAINT FK_VISITA_IDOSO
    FOREIGN KEY (ID_IDOSO) REFERENCES T_IDOSO (ID);

-- T_PRESTADOR -> T_VISITA
ALTER TABLE T_VISITA
    ADD CONSTRAINT FK_VISITA_PRESTADOR
    FOREIGN KEY (ID_PRESTADOR) REFERENCES T_PRESTADOR (ID);

-- T_IDOSO -> T_SOLICITACAO
ALTER TABLE T_SOLICITACAO
    ADD CONSTRAINT FK_SOLICITACAO_IDOSO
    FOREIGN KEY (ID_IDOSO) REFERENCES T_IDOSO (ID);

-- T_GUARDIAO -> T_SOLICITACAO (excluir o guardião mantém o histórico)
ALTER TABLE T_SOLICITACAO
    ADD CONSTRAINT FK_SOLICITACAO_GUARDIAO
    FOREIGN KEY (ID_GUARDIAO_RESPOSTA) REFERENCES T_GUARDIAO (ID)
    ON DELETE SET NULL;

-- T_VISITA -> T_SOLICITACAO
ALTER TABLE T_SOLICITACAO
    ADD CONSTRAINT FK_SOLICITACAO_VISITA
    FOREIGN KEY (ID_VISITA) REFERENCES T_VISITA (ID)
    ON DELETE SET NULL;


