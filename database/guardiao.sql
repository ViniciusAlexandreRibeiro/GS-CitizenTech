-- 1. Valor protegido por idoso
SELECT I.NOME,
       COUNT(S.ID) AS QTD_BLOQUEIOS,
       NVL(SUM(S.VALOR), 0) AS VALOR_PROTEGIDO
  FROM T_IDOSO I
 INNER JOIN T_SOLICITACAO S ON S.ID_IDOSO = I.ID
 WHERE S.STATUS = 'BLOQUEADA'
 GROUP BY I.NOME
 ORDER BY VALOR_PROTEGIDO DESC;

-- 2. Tentativas barradas na porta por bairro
SELECT I.BAIRRO, COUNT(*) AS QTD_TENTATIVAS
  FROM T_SOLICITACAO S
 INNER JOIN T_IDOSO I ON I.ID = S.ID_IDOSO
 WHERE S.TIPO = 'VISITA'
 GROUP BY I.BAIRRO
 ORDER BY QTD_TENTATIVAS DESC;

-- 3. Pedidos por tipo e decisão
SELECT TIPO,
       COUNT(*) AS TOTAL,
       SUM(CASE WHEN STATUS = 'BLOQUEADA' THEN 1 ELSE 0 END) AS BLOQUEADAS,
       SUM(CASE WHEN STATUS = 'LIBERADA' THEN 1 ELSE 0 END) AS LIBERADAS,
       SUM(CASE WHEN STATUS = 'PENDENTE' THEN 1 ELSE 0 END) AS PENDENTES
  FROM T_SOLICITACAO
 GROUP BY TIPO
 ORDER BY TOTAL DESC;

-- 4. Tempo médio de resposta por guardião (em minutos)
SELECT G.NOME,
       COUNT(*) AS QTD_RESPOSTAS,
       ROUND(AVG((S.DATA_RESPOSTA - S.DATA_ABERTURA) * 24 * 60), 1) AS MINUTOS_MEDIOS
  FROM T_GUARDIAO G
 INNER JOIN T_SOLICITACAO S ON S.ID_GUARDIAO_RESPOSTA = G.ID
 WHERE S.DATA_RESPOSTA IS NOT NULL
 GROUP BY G.NOME
 ORDER BY MINUTOS_MEDIOS;

-- 5. Contatos suspeitos que aparecem mais de uma vez
SELECT CONTATO_SUSPEITO,
       MAX(TIPO) AS TIPO,
       COUNT(DISTINCT ID_IDOSO) AS QTD_IDOSOS,
       COUNT(*) AS QTD_BLOQUEIOS,
       MAX(DATA_ABERTURA) AS ULTIMO_USO
  FROM T_SOLICITACAO
 WHERE STATUS = 'BLOQUEADA'
   AND CONTATO_SUSPEITO IN (SELECT CONTATO_SUSPEITO
                              FROM T_SOLICITACAO
                             WHERE CONTATO_SUSPEITO IS NOT NULL
                             GROUP BY CONTATO_SUSPEITO
                            HAVING COUNT(*) > 1)
 GROUP BY CONTATO_SUSPEITO
 ORDER BY QTD_BLOQUEIOS DESC;

-- 6. Idosos sem nenhum guardião
SELECT I.ID, I.NOME, I.BAIRRO
  FROM T_IDOSO I
  LEFT JOIN T_VINCULO V ON V.ID_IDOSO = I.ID
 WHERE V.ID_IDOSO IS NULL
 ORDER BY I.NOME;
