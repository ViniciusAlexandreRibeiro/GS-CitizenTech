SELECT 'IDOSOS' AS TABELA, COUNT(*) AS QTD FROM T_IDOSO
UNION ALL SELECT 'GUARDIOES', COUNT(*) FROM T_GUARDIAO
UNION ALL SELECT 'VINCULOS', COUNT(*) FROM T_VINCULO
UNION ALL SELECT 'EMPRESAS', COUNT(*) FROM T_EMPRESA
